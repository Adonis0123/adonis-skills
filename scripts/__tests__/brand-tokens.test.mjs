import assert from "node:assert/strict";
import test from "node:test";
import {
  contrastRatio,
  findBrandIssues,
  renderBrandTokensCss,
  renderThemeRolesCss,
  renderDesignMd,
  resolveHex,
} from "../lib/brand-tokens.mjs";

const palette = {
  colors: [
    {
      id: "cream",
      hex: "#F6F1E7",
      group: "neutral",
      name: { en: "Cream" },
      source: "templates",
    },
    {
      id: "ink",
      hex: "#1E2A44",
      group: "neutral",
      name: { en: "Ink" },
      source: "BRAND.md",
    },
    {
      id: "sage",
      hex: "#7FB685",
      group: "personal",
      name: { en: "Sage" },
      source: "BRAND.md",
    },
  ],
};

const theme = (light, dark) => ({
  modes: { light, ...(dark ? { dark } : {}) },
  contrast: { text: 4.5, pairs: [["foreground", "background"]] },
});

test("contrastRatio matches WCAG reference values", () => {
  assert.equal(contrastRatio("#000000", "#ffffff").toFixed(2), "21.00");
  assert.equal(contrastRatio("#1E2A44", "#F6F1E7").toFixed(2), "12.69");
});

test("a valid theme has no issues and resolves @role references", () => {
  const t = theme(
    {
      background: "{cream}",
      foreground: "{ink}",
      card: "@background",
      border: { mix: "ink", pct: 14 },
    },
    { background: "{ink}", foreground: "{cream}", card: "@background" },
  );
  assert.deepEqual(findBrandIssues(palette, t), []);
  assert.equal(resolveHex(palette, t, "dark", "card"), "#1e2a44");
  assert.equal(resolveHex(palette, t, "light", "border"), null);
});

test("reports unknown palette ids with a fix hint", () => {
  const [issue] = findBrandIssues(
    palette,
    theme({ background: "{cream}", foreground: "{forest}" }),
  );
  assert.match(issue, /light\.foreground refers to "forest"/);
  assert.match(issue, /add it there first/);
});

test("reports text pairs below the contrast minimum", () => {
  const [issue] = findBrandIssues(
    palette,
    theme({ background: "{cream}", foreground: "{sage}" }),
  );
  assert.match(issue, /below 4\.5:1/);
  assert.match(issue, /2\.\d\d:1/);
});

test("rejects bad mix percentages, unknown roles, duplicates, and bad hex", () => {
  const broken = {
    colors: [
      ...palette.colors,
      {
        id: "ink",
        hex: "#12345",
        group: "neutral",
        name: { en: "Dup" },
        source: "x",
      },
    ],
  };
  const issues = findBrandIssues(
    broken,
    theme({
      background: "{cream}",
      foreground: "{ink}",
      border: { mix: "ink", pct: 0 },
      card: "@nope",
    }),
  );
  assert.ok(issues.some((issue) => issue.includes('duplicate id "ink"')));
  assert.ok(issues.some((issue) => issue.includes("must be #rrggbb")));
  assert.ok(issues.some((issue) => issue.includes("pct must be 1-100")));
  assert.ok(issues.some((issue) => issue.includes('unknown role "@nope"')));
});

test("generated CSS carries provenance and maps roles to brand tokens", () => {
  const source = { commit: "4340586c8087bb5d8d7823601beccaa0a243d4e3" };
  const brandCss = renderBrandTokensCss(palette, source);
  assert.match(brandCss, /GENERATED .* adonis-brand@4340586c8087/);
  assert.match(brandCss, /--brand-ink: #1e2a44; \/\* Ink \(neutral\) \*\//);

  const rolesCss = renderThemeRolesCss(
    theme(
      {
        background: "{cream}",
        foreground: "{ink}",
        border: { mix: "ink", pct: 14 },
      },
      { background: "{ink}", card: "@background" },
    ),
    source,
  );
  assert.match(
    rolesCss,
    /--background: var\(--brand-cream\); \/\* \{cream\} \*\//,
  );
  assert.match(
    rolesCss,
    /--border: color-mix\(in oklab, var\(--brand-ink\) 14%, transparent\);/,
  );
  assert.match(
    rolesCss,
    /\.dark,\n:root\[data-theme="dark"\] \{\n {2}--background: var\(--brand-ink\);/,
  );
  assert.match(rolesCss, /--card: var\(--background\);/);
});

test("renderDesignMd injects light and dark colors before typography", () => {
  const designSource = [
    "---",
    "version: alpha",
    "name: Demo",
    "typography:",
    "  body:",
    "    fontSize: 15px",
    "---",
    "",
    "## Overview",
    "",
  ].join("\n");
  const out = renderDesignMd(
    designSource,
    palette,
    theme(
      {
        background: "{cream}",
        foreground: "{ink}",
        overlay: { mix: "ink", pct: 30 },
      },
      { background: "{ink}", card: "@background" },
    ),
    { commit: "0123456789abcdef" },
  );
  assert.match(
    out,
    /^---\n# GENERATED by scripts\/sync-brand-tokens\.mjs from adonis-brand@0123456789ab/,
  );
  assert.match(
    out,
    /colors:\n {2}background: "#f6f1e7"\n {2}foreground: "#1e2a44"\n {2}background-dark: "#1e2a44"\n {2}card-dark: "#1e2a44"\ntypography:/,
  );
  assert.doesNotMatch(out, /overlay/);
  assert.match(out, /---\n\n## Overview\n$/);
});

test("renderDesignMd rejects a source that hardcodes colors", () => {
  assert.throws(
    () =>
      renderDesignMd(
        '---\nname: Demo\ncolors:\n  primary: "#000000"\n---\n',
        palette,
        theme({ background: "{cream}" }),
        null,
      ),
    /must not define `colors`/,
  );
});
